# Define constants
INDENT = "    "  # 4-space indentation
GENERATOR_MESSAGE_LINES = [
    "This file was automatically generated by the Evolution Generator.",
    "The Evolution Generator is used to automate the creation of consistent, reliable code.",
    "Any changes made to this file will be overwritten.",
]


def _format_generator_header(prefix: str) -> str:
    return "".join(f"{prefix}{line}\n" for line in GENERATOR_MESSAGE_LINES) + "\n"


# Add Generator comment at the start of the file
def add_generator_comment() -> str:
    return _format_generator_header("// ")


# Add Generator YAML header at the start of the file
def add_generator_yaml_header() -> str:
    return _format_generator_header("# ")


# Error when any required fields values are None
def error_when_missing_required_fields(
    required_fields_names, required_fields_values, row_number: int
):
    if any(field is None for field in required_fields_values):
        missing_fields = [
            field_name
            for field_value, field_name in zip(
                required_fields_values, required_fields_names
            )
            if field_value is None
        ]
        raise Exception(
            f"Required field is missing in row {row_number}. Missing fields: {missing_fields}"
        )


# Generate output file
def generate_output_file(ts_code: str, output_file: str):
    try:
        with open(output_file, mode="w", encoding="utf-8", newline="\n") as ts_file:
            ts_file.write(ts_code)

        print(f"Generated {output_file} successfully")

    except Exception as e:
        print(f"Error generating {output_file}: {e}")
        raise e


# Delete file if exists
def delete_file_if_exists(file_path: str) -> None:
    if os.path.isfile(file_path):
        os.remove(file_path)


# Check if the output file is an TypeScript file
def is_ts_file(file: str) -> None:
    if not (file.endswith(".ts") or file.endswith(".tsx")):
        raise Exception(
            f"Invalid output file extension for {file} : must be an TypeScript .ts or .tsx file"
        )


def load_survey_definition(reader: ExcelSurveyDefinitionReader) -> SurveyDefinition:
    """
    Build a SurveyDefinition from the languages and tables read by `reader`.

    Raises on the problems the reader finds (missing table, missing required field),
    and `pydantic.ValidationError` when the languages or a table's rows don't pass
    their checks.
    The returned instance is already validated; callers don't need to check it again.
    """
    return SurveyDefinition(
        languages=reader.read_languages(),
        sections=reader.read_table("Sections", SECTION_REQUIRED_FIELD_NAMES),
        conditionals=reader.read_table(
            "Conditionals", CONDITIONAL_REQUIRED_FIELD_NAMES
        ),
        labels=reader.read_table("Labels", LABEL_REQUIRED_FIELD_NAMES),
        choices=reader.read_table("Choices", CHOICE_REQUIRED_FIELD_NAMES),
    )


# Function to clean text of markdown characters
def clean_text(text) -> str:
    if text is None:
        return ""
    return (
        str(text)  # This ensures that number input doesn't break everything
        .replace("**", "")
        .replace("__green", "")
        .replace("__red", "")
        .replace("__", "")
    )


def get_label_context_flags(
    *,
    labels: Iterable[Optional[str]] = (),
    labels_one: Iterable[Optional[str]] = (),
) -> Tuple[bool, bool, bool, bool]:
    """
    Detect whether label strings require dynamic i18n context.

    `labels` and `labels_one` are the labels and the `label_one` labels to check, in
    any languages (e.g. `labels=[label_fr, label_en]`); a missing label is None.

    Returns:
        (has_nickname, has_count, has_gender_context, has_label_one)

    Notes:
        - We treat `{{nickname}}` and `{{count}}` as interpolation tokens.
        - Gender context detection accepts spaces around the colon (LibreOffice can
          insert them), matching `{{gender:...}}`, `{{gender :...}}`,
          `{{gender: ...}}`, and `{{gender : ...}}`.
        - `has_label_one` is true if any of the *_one labels are non-empty.
    """

    labels_one = list(labels_one)
    label_text = "".join(text or "" for text in [*labels, *labels_one])

    has_nickname = re.search(r"\{\{\s*nickname\s*\}\}", label_text) is not None
    has_count = re.search(r"\{\{\s*count\s*\}\}", label_text) is not None
    has_gender_context = re.search(r"\{\{\s*gender\s*:\s*", label_text) is not None
    has_label_one = any((label_one or "").strip() for label_one in labels_one)
    return has_nickname, has_count, has_gender_context, has_label_one


def generate_label_typescript_with_context(
    *,
    property_name: str,
    translation_key: str,
    base_indent: str,
    has_nickname: bool,
    has_count: bool,
    has_gender_context: bool,
    has_label_one: bool,
    gender_context_expression: str | None = None,
) -> str:
    """
    Generate a TypeScript i18n property (`label` / `text`) with optional runtime context.

    If no runtime context is needed, this returns a simple `(t) => t('...')` snippet.
    Otherwise, it returns a full function `(t, interview, path) => { ... }` that
    computes the required context and passes it to `t('...', { ... })`.
    """

    needs_runtime_context = (
        has_nickname or has_count or has_gender_context or has_label_one
    )
    if not needs_runtime_context:
        return f"{base_indent}{property_name}: (t: TFunction) => t('{translation_key}')"

    initial_assignations = ""
    additional_t_context = ""

    const_indent = f"{base_indent}{INDENT}"
    return_indent = f"{base_indent}{INDENT}"
    context_indent = f"{base_indent}{INDENT}{INDENT}"

    if has_nickname or has_gender_context:
        initial_assignations += f"{const_indent}const activePerson = odSurveyHelpers.getPerson({{ interview, path }});\n"

    if has_nickname:
        initial_assignations += f"{const_indent}const nickname = _escape(activePerson?.nickname || t('survey:noNickname'));\n"
        additional_t_context += f"{context_indent}nickname,\n"

    if has_label_one or has_count:
        initial_assignations += f"{const_indent}const countPersons = odSurveyHelpers.countPersons({{ interview }});\n"
        additional_t_context += f"{context_indent}count: countPersons,\n"

    if has_gender_context:
        context_expr = gender_context_expression or "undefined"
        additional_t_context += f"{context_indent}context: {context_expr},\n"

    return (
        f"{base_indent}{property_name}: (t: TFunction, interview, path) => {{\n"
        f"{initial_assignations}"
        f"{return_indent}return t('{translation_key}', {{\n"
        f"{additional_t_context}"
        f"{return_indent}}});\n"
        f"{base_indent}}}"
    )
