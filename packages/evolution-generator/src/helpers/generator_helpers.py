# Get values from the row
def get_values_from_row(row, headers) -> tuple:
    try:
        # Create a dictionary from the row values and headers
        row_dict = dict(zip(headers, (cell.value for cell in row)))
        values = []  # List of values from the row

        # Get values from the row dictionary
        for header in headers:
            header = row_dict[header]
            values.append(header)

        return values

    except Exception as e:
        print(f"Error getting values from row: {e}")
        raise e


# Error when any required fields values are None
def error_when_missing_required_fields(
    required_fields_names, required_fields_values, row_number: int
):
    if any(field is None for field in required_fields_values):
        missing_fields = [
            field_name
            for field_value, field_name in zip(
                required_fields_values, required_fields_names
            )
            if field_value is None
        ]
        raise Exception(
            f"Required field is missing in row {row_number}. Missing fields: {missing_fields}"
        )


# Generate output file
def generate_output_file(ts_code: str, output_file: str):
    try:
        with open(output_file, mode="w", encoding="utf-8", newline="\n") as ts_file:
            ts_file.write(ts_code)

        print(f"Generated {output_file} successfully")

    except Exception as e:
        print(f"Error generating {output_file}: {e}")
        raise e


# Delete file if exists
def delete_file_if_exists(file_path: str) -> None:
    if os.path.isfile(file_path):
        os.remove(file_path)


# Check if the input file is an Excel file
def is_excel_file(file: str) -> None:
    file_lower = file.lower()
    if not (
        file_lower.endswith(".xlsx")
        or file_lower.endswith(".xlsm")
        or file_lower.endswith(".xltx")
        or file_lower.endswith(".xltm")
    ):
        raise Exception(
            f"Invalid input file extension for {file} : must be an Excel 2010+ .xlsx, .xlsm, .xltx or .xltm file"
        )


# Check if the output file is an TypeScript file
def is_ts_file(file: str) -> None:
    if not (file.endswith(".ts") or file.endswith(".tsx")):
        raise Exception(
            f"Invalid output file extension for {file} : must be an TypeScript .ts or .tsx file"
        )


# Check if the sheet exists
def sheet_exists(workbook: Workbook, sheet_name: str) -> None:
    if sheet_name not in workbook.sheetnames:
        raise Exception(f"Sheet with name {sheet_name} does not exist")


# Get workbook from Excel file
def get_workbook(input_file: str) -> Workbook:
    workbook = openpyxl.load_workbook(input_file, data_only=True)
    return workbook


# Get headers from the first row
def get_headers(sheet, expected_headers: List[str], sheet_name: str) -> List[str]:
    # Get headers from the first row
    current_headers = [cell.value for cell in list(sheet.rows)[0]]

    # Check if the headers are valid
    for expected in expected_headers:
        if not expected in current_headers:
            raise Exception(
                f"Missing expected header in {sheet_name} sheet: {expected}"
            )

    return current_headers


def _read_sheet_rows(
    workbook: Workbook, sheet_name: str, expected_headers
) -> List[dict]:
    """Read every data row of `sheet_name` (row 1 is the header) as a dict keyed by its headers.

    Trailing rows whose cells are all blank are dropped: openpyxl's row count can
    include a styled-but-otherwise-empty row past the real data, which would otherwise
    be read as a row missing every required field. Interior blank rows are kept
    (still invalid if the sheet requires values).
    """
    sheet_exists(workbook, sheet_name)
    sheet = workbook[sheet_name]
    headers = get_headers(
        sheet, expected_headers=expected_headers, sheet_name=sheet_name
    )
    rows = list(sheet.rows)[1:]
    while len(rows) > 1 and all(cell.value is None for cell in rows[-1]):
        rows.pop()
    return [
        dict(zip(headers, get_values_from_row(row, headers), strict=True))
        for row in rows
    ]


# Prefix of the translated columns the survey languages are read from, in the Widgets
# sheet: one column per language, e.g. label::fr, label::en.
LANGUAGE_COLUMN_PREFIX = "label::"


def read_survey_languages(workbook: Workbook) -> tuple[str, ...]:
    """
    Read the survey languages from the Widgets sheet: one per `label::<language>`
    column, in column order, e.g. ("fr", "en") for label::fr and label::en.

    The workbook carries its own languages, so a survey is checked the same way from
    any app or config. Raises if the sheet has no such column.
    """
    sheet_exists(workbook, "Widgets")
    headers = [cell.value for cell in next(workbook["Widgets"].iter_rows(max_row=1))]
    languages = tuple(
        header.removeprefix(LANGUAGE_COLUMN_PREFIX)
        for header in headers
        if isinstance(header, str) and header.startswith(LANGUAGE_COLUMN_PREFIX)
    )
    if not languages:
        raise Exception(
            "Missing label::<language> columns in Widgets sheet: the survey languages "
            "are read from them, e.g. label::fr and label::en."
        )
    return languages


def _read_optional_sheet_rows(
    workbook: Workbook, sheet_name: str, expected_headers
) -> List[dict]:
    """Like _read_sheet_rows, but a missing sheet is read as an empty table (e.g. a survey without any slider has no InputRange sheet)."""
    if sheet_name not in workbook.sheetnames:
        return []
    return _read_sheet_rows(workbook, sheet_name, expected_headers)


def load_survey_definition(excel_file_path: str) -> SurveyDefinition:
    """
    Build a SurveyDefinition from an Excel file's sheets, in the survey languages read
    from the Widgets sheet (see read_survey_languages). An optional sheet that is
    missing is read as an empty table.

    Raises on the same problems as get_data_from_excel/get_headers (invalid file,
    missing required sheet, missing/too few headers), and `pydantic.ValidationError`
    when the languages or a sheet's rows don't pass their checks (see
    survey_definition.py, sections_definition.py, ...).
    The returned instance is already validated; callers don't need to check it again.
    """
    is_excel_file(excel_file_path)
    workbook = get_workbook(excel_file_path)

    return SurveyDefinition(
        languages=read_survey_languages(workbook),
        sections=_read_sheet_rows(workbook, "Sections", SECTION_REQUIRED_FIELD_NAMES),
        conditionals=_read_sheet_rows(
            workbook, "Conditionals", CONDITIONAL_REQUIRED_FIELD_NAMES
        ),
        labels=_read_sheet_rows(workbook, "Labels", LABEL_REQUIRED_FIELD_NAMES),
        choices=_read_sheet_rows(workbook, "Choices", CHOICE_REQUIRED_FIELD_NAMES),
        input_ranges=_read_optional_sheet_rows(
            workbook, "InputRange", INPUT_RANGE_REQUIRED_FIELD_NAMES
        ),
    )


# Function to clean text of markdown characters
def clean_text(text) -> str:
    if text is None:
        return ""
    return (
        str(text)  # This ensures that number input doesn't break everything
        .replace("**", "")
        .replace("__green", "")
        .replace("__red", "")
        .replace("__", "")
    )


def get_label_context_flags(
    *,
    labels: Iterable[Optional[str]] = (),
    labels_one: Iterable[Optional[str]] = (),
) -> Tuple[bool, bool, bool, bool]:
    """
    Detect whether label strings require dynamic i18n context.

    `labels` and `labels_one` are the labels and the `label_one` labels to check, in
    any languages (e.g. `labels=[label_fr, label_en]`); a missing label is None.

    Returns:
        (has_nickname, has_count, has_gender_context, has_label_one)

    Notes:
        - We treat `{{nickname}}` and `{{count}}` as interpolation tokens.
        - Gender context detection accepts spaces around the colon (LibreOffice can
          insert them), matching `{{gender:...}}`, `{{gender :...}}`,
          `{{gender: ...}}`, and `{{gender : ...}}`.
        - `has_label_one` is true if any of the *_one labels are non-empty.
    """

    labels_one = list(labels_one)
    label_text = "".join(text or "" for text in [*labels, *labels_one])

    has_nickname = re.search(r"\{\{\s*nickname\s*\}\}", label_text) is not None
    has_count = re.search(r"\{\{\s*count\s*\}\}", label_text) is not None
    has_gender_context = re.search(r"\{\{\s*gender\s*:\s*", label_text) is not None
    has_label_one = any((label_one or "").strip() for label_one in labels_one)
    return has_nickname, has_count, has_gender_context, has_label_one


def generate_label_typescript_with_context(
    *,
    property_name: str,
    translation_key: str,
    base_indent: str,
    has_nickname: bool,
    has_count: bool,
    has_gender_context: bool,
    has_label_one: bool,
    gender_context_expression: str | None = None,
) -> str:
    """
    Generate a TypeScript i18n property (`label` / `text`) with optional runtime context.

    If no runtime context is needed, this returns a simple `(t) => t('...')` snippet.
    Otherwise, it returns a full function `(t, interview, path) => { ... }` that
    computes the required context and passes it to `t('...', { ... })`.
    """

    needs_runtime_context = (
        has_nickname or has_count or has_gender_context or has_label_one
    )
    if not needs_runtime_context:
        return f"{base_indent}{property_name}: (t: TFunction) => t('{translation_key}')"

    initial_assignations = ""
    additional_t_context = ""

    const_indent = f"{base_indent}{INDENT}"
    return_indent = f"{base_indent}{INDENT}"
    context_indent = f"{base_indent}{INDENT}{INDENT}"

    if has_nickname or has_gender_context:
        initial_assignations += f"{const_indent}const activePerson = odSurveyHelpers.getPerson({{ interview, path }});\n"

    if has_nickname:
        initial_assignations += f"{const_indent}const nickname = _escape(activePerson?.nickname || t('survey:noNickname'));\n"
        additional_t_context += f"{context_indent}nickname,\n"

    if has_label_one or has_count:
        initial_assignations += f"{const_indent}const countPersons = odSurveyHelpers.countPersons({{ interview }});\n"
        additional_t_context += f"{context_indent}count: countPersons,\n"

    if has_gender_context:
        context_expr = gender_context_expression or "undefined"
        additional_t_context += f"{context_indent}context: {context_expr},\n"

    return (
        f"{base_indent}{property_name}: (t: TFunction, interview, path) => {{\n"
        f"{initial_assignations}"
        f"{return_indent}return t('{translation_key}', {{\n"
        f"{additional_t_context}"
        f"{return_indent}}});\n"
        f"{base_indent}}}"
    )
